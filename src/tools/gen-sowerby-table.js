// Regenerate lib/sowerby-table.js from Sowerby's sign table.
//   node src/tools/gen-sowerby-table.js [path/to/sowerby_system.cex]
// Default source: src/assets/sowerby_system.cex, a copy of
// mousike/src/mousike/data/sowerby_system.cex. As in mousike's `load_table`, this reads the
// symbol column (not the hex column, which has malformed entries) and the description column.
const fs = require("node:fs");
const path = require("node:path");

const src = process.argv[2] || path.join(__dirname, "..", "assets", "sowerby_system.cex");
const PREFIX = "urn:cite2:zst:";

const table = {};
const lines = fs.readFileSync(src, "utf8").split(/\r?\n/).slice(1);
for (const line of lines) {
  if (!line.trim()) continue;
  const cols = line.split("|");
  let urn = cols[0].trim();
  if (!urn) continue;
  if (urn.startsWith(PREFIX)) urn = urn.slice(PREFIX.length);
  table[urn] = [cols[1].trim(), cols[4].trim()];
}

const body = Object.entries(table)
  .map(([k, [sym, name]]) => `    ${JSON.stringify(k)}: [${JSON.stringify(sym)}, ${JSON.stringify(name)}],`)
  .join("\n");

const out = `/*
 * GENERATED by src/tools/gen-sowerby-table.js — do not edit by hand.
 * Source: sowerby_system.cex from the mousike project (Zach Sowerby's notation table).
 * Maps short note URNs (e.g. "gvn:11.1") to [unicode sign, description].
 */
(function (root, factory) {
  if (typeof module === "object" && module.exports) module.exports = factory();
  else root.AgmSowerbyTable = factory();
})(typeof self !== "undefined" ? self : this, function () {
  "use strict";
  return {
${body}
  };
});
`;
const dest = path.join(__dirname, "..", "lib", "sowerby-table.js");
fs.writeFileSync(dest, out);
console.log(`wrote ${path.relative(process.cwd(), dest)} (${Object.keys(table).length} signs)`);
